# ---------- 知识点：创建与索引 ----------
scores = [78, 92, 65, 88, 59]
print(scores)        # [78, 92, 65, 88, 59]
print(scores[0])     # 78   第一个
print(scores[-1])    # 59   最后一个（负数从右边数）


# ---------- 知识点：切片 ----------
# scores[start:end] 取从 start 到 end 前一个元素
print(scores[1:3])   # [92, 65]
print(scores[:2])    # [78, 92]   从头开始
print(scores[2:])    # [65, 88, 59] 到最后


# ---------- 知识点：增删改 ----------
scores.append(100)       # 末尾追加
print(scores)            # [78, 92, 65, 88, 59, 100]

scores.remove(59)        # 删除指定的值
print(scores)

scores[0] = 80           # 按下标改
print(scores)


# ---------- 知识点：内置函数 ----------
print(len(scores))       # 个数
print(sum(scores))       # 总和
print(max(scores))       # 最大值
print(min(scores))       # 最小值
print(sum(scores) / len(scores))   # 平均值


# ---------- 知识点：排序 ----------
print(sorted(scores))            # 返回新列表，从小到大
print(sorted(scores, reverse=True))  # 从大到小


# ---------- 知识点：遍历（for 循环）----------
# 冒号 + 缩进 是 Python 的语法特征：缩进的部分都属于循环体
for s in scores:
    print(f"分数：{s}")


