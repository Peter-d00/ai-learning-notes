# ---------- 知识点：变量 ----------
# 变量就是一个"贴了标签的盒子"，用来存数据。
# Python 不用提前声明类型，赋值那一刻类型就确定了。
name = "刘煜贤"
age = 22
height = 1.75
is_learning = True

# type() 可以查看一个变量的类型
print(type(name))         # <class 'str'>    字符串
print(type(age))          # <class 'int'>    整数
print(type(height))       # <class 'float'>  小数
print(type(is_learning))  # <class 'bool'>   布尔值（True / False）


# ---------- 知识点：f-string ----------
# 字符串前面加 f，大括号里的变量会被替换成它的值
print(f"{name} 今年 {age} 岁，身高 {height} 米")


# ---------- 知识点：类型转换 ----------
# int("18") 把字符串变成整数；反过来用 str(18)
text = "18"
number = int(text)
print(number * 2)   # 输出 36，不是 "1818"


# ---------- 知识点：字符串常用操作 ----------
sentence = "  Python 是一门好用的语言  "
print(sentence.strip())              # 去掉首尾空格
print(sentence.strip().split(" "))   # 按空格切开，变成列表
print(len("Python"))                 # 6，求长度


