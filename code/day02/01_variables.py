# 不用手数的：
start = text.index("AI")          # 6
length = len("AI 应用开发")        # 7
print(text[ start : start + length ])  # text[6:13]
# 封装成函数：
def cut(text, target):
    start = text.index(target)
    return text[start:start + len(target)]

print(cut("我正在学习 AI 应用开发，方向是后端", "AI 应用开发"))
print(cut("我学 AI 应用开发，每天四小时", "AI 应用开发"))
print(cut("AI 应用开发是我接下来一年的目标", "AI 应用开发"))

