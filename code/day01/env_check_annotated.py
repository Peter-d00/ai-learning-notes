# ---------- 第 3 部分：主程序（从这里开始一行行往下执行）----------

line("1. 看看我的电脑")     # 调用上面定义的函数，括号里传参数

# 【知识点】f-string：字符串前面加一个 f，里面的大括号会被当成代码执行，
# 结果直接填进字符串里。这是 Python 里最常用的拼接字符串的方式。
#
# sys.version 形如 "3.12.10 (main, ...)"，
# .split() 按空格切成一堆片段，[0] 取第一个 —— 也就是 "3.12.10"
print(f"版本   : {sys.version.split()[0]}")

# sys.executable = 当前正在运行的 python.exe 的完整路径。
# 这一行能证明你用的是"真 Python"，不是微软商店那个占位程序。
print(f"解释器 : {sys.executable}")

# platform.system() 返回 "Windows"，platform.release() 返回 "11"
print(f"系统   : {platform.system()} {platform.release()}")


line("2. 基础语法自检")

# 【知识点】列表（list）：用方括号装一串数据，有顺序，可以修改。
# 索引从 0 开始：numbers[0] 是 3，numbers[-1] 是最后一个 7。
numbers = [3, 8, 15, 22, 7]

print(f"列表   : {numbers}")
print(f"总和   : {sum(numbers)}")    # 内置函数 sum 直接求和 → 55
print(f"最大值 : {max(numbers)}")    # 内置函数 max 取最大 → 22

# 【知识点】:.2f 是格式化指令，表示"保留 2 位小数"。
# 把 .2f 换成 .0f 就变成整数显示，换成 .4f 就显示 4 位。
print(f"平均值 : {average(numbers):.2f}")   # 55/5 = 11.00


line("3. 打卡")

# 【知识点】datetime.now() 取当前时间（一个对象），
# .strftime() 把它变成指定格式的字符串：
#   %Y 四位年份   %m 两位月份   %d 两位日期
today = datetime.now().strftime("%Y-%m-%d")
print(f"日期   : {today}")
print("状态   : 环境就绪，可以开始写代码了")


