# ---------- 第 1 部分：导入工具箱 ----------
# 【知识点】import = 把 Python 自带的"工具箱"拿进来用。
# 这些是标准库，装完 Python 就有，不需要额外下载。
#   sys      ：和解释器本身有关的东西（版本、路径、参数）
#   platform ：查询操作系统信息
#   datetime ：处理日期和时间
import platform
import sys

# 【知识点】from A import B = 只从工具箱 A 里取出 B 这一件工具。
# 好处是后面直接写 datetime 就行，不用写 datetime.datetime。
from datetime import datetime


# ---------- 第 2 部分：定义两个函数 ----------
# 【知识点】def = 定义一个函数：把一段代码打包、起名字，以后可以反复调用。
# 结构拆开看：
#   def        关键字，表示"我要定义一个函数"
#   line       函数名，你自己起（用小写+下划线）
#   (title)    参数，调用时要传进来的东西
#   : str      类型注解，说明 title 应该是字符串（写不写都能跑，但写了更好读）
#   -> None    返回值类型注解，None 表示"不返回东西，只做事"
def line(title: str) -> None:
    """打印一个带下划线的小标题。

    三个引号括起来的是"文档字符串"（docstring）。
    它的作用：别人把鼠标停在 line( 上时，就能看到这段说明。
    """
    print(f"\n{title}")   # \n 是换行符：先空一行，再打印标题
    print("-" * 40)       # 字符串 * 数字 = 重复拼接，这里生成 40 个横线


