# ============================================================
# Day 03 · 练习 1：字典（dict）
# ------------------------------------------------------------
# 字典是"键值对"：用一个标签（键）去取一个值。
# 现实里的例子：学生档案、商品信息、API 返回的 JSON，全是字典。
#
# 运行：python code/day03/01_dict.py
# ============================================================


# ---------- 知识点：创建与访问 ----------
student = {
    "name": "刘煜贤",
    "age": 22,
    "city": "赣州",
}

print(student)              # {'name': '刘煜贤', ...}
print(student["name"])      # 刘煜贤（用键取值）
print(len(student))         # 3（有几个键值对）

# 【关键】用 [] 取不存在的键会报错 KeyError
# 用 .get() 则不会，还能给默认值
print(student.get("phone", "没填"))   # 没填


# ---------- 知识点：增、改、删 ----------
student["goal"] = "深圳"      # 键不存在 = 新增
student["age"] = 23           # 键已存在 = 修改
print(student)

del student["city"]           # 删除
print(student)


# ---------- 知识点：遍历 ----------
for key in student:                 # 只拿键
    print("键：", key)

for key, value in student.items():  # 同时拿键和值（最常用）
    print(f"{key} = {value}")


# ---------- 知识点：判断有没有 ----------
print("name" in student)      # True
print("phone" in student)     # False


# ---------- 知识点：字典和 JSON 的关系 ----------
# API 返回的数据长这样：{"code": 0, "data": {...}}
# 用 json.loads() 解析后就是 Python 的字典
import json
text = '{"name": "刘煜贤", "age": 22}'
data = json.loads(text)
print(data["name"])           # 刘煜贤


