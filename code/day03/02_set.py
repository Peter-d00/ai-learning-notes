# ---------- 知识点：创建与自动去重 ----------
nums = {1, 2, 2, 3, 3, 3}
print(nums)             # {1, 2, 3}  重复的自动去掉

# 从列表转集合 = 去重（但顺序不保证）
scores = [78, 92, 78, 65, 92]
print(set(scores))      # {65, 78, 92}


# ---------- 知识点：判断是否存在 ----------
print(92 in set(scores))    # True
# 集合判断比列表快得多，数据量大时差别明显


# ---------- 知识点：交集、并集、差集 ----------
a = {1, 2, 3, 4}
b = {3, 4, 5, 6}

print(a & b)    # {3, 4}   交集：两边都有
print(a | b)    # {1,2,3,4,5,6}  并集：合起来
print(a - b)    # {1, 2}   差集：a 有但 b 没有


# ---------- 知识点：增删 ----------
s = {1, 2}
s.add(3)
s.discard(1)    # 不存在也不报错
print(s)        # {2, 3}


